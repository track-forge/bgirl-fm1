"""Deterministically embed our short PCM phrase; never called by the audio renderer."""
import struct, wave
from pathlib import Path
root=Path(__file__).resolve().parent
with wave.open(str(root/'phrase.wav')) as w:
    assert (w.getnchannels(),w.getsampwidth(),w.getframerate())==(1,2,22050)
    samples=struct.unpack('<'+'h'*w.getnframes(),w.readframes(w.getnframes()))
assert 0 < len(samples) <= 22050*8
(root/'phrase.h').write_text('/* SPDX-License-Identifier: CC0-1.0\n * Original synthetic speech; see README.md. Generated by embed.py. */\n#pragma once\n#include <stdint.h>\n#define PHRASE_FRAMES '+str(len(samples))+'u\nstatic const int16_t phrase_pcm[PHRASE_FRAMES]={\n'+''.join(','.join(map(str,samples[i:i+24]))+',\n' for i in range(0,len(samples),24))+'};\n')
print(f'{len(samples)} frames, {len(samples)*2} PCM bytes, {len(samples)/22050:.3f}s')
