"""Serialize the fixed Miami hardware pack in one Felucca sample slot."""
import struct
import zlib

MAGIC = b'BGVB'
HEADER_SIZE = 512
SLOT_SIZE = 81920


def package(dest, report):
    identity = bytes.fromhex(report['bank_sha256'][:16])
    audio = (dest / 'bank.ima').read_bytes()
    if identity.hex() != 'bb8f8cb449511455' or len(audio) != 68454:
        raise ValueError('unexpected Miami hardware bank content')
    entries = b''.join(struct.pack('<III', e['start'], e['end'], e['checkpoint'])
                       for e in report['entries'])
    grid = b''.join(struct.pack('<I', e['state']) for e in report['grid_checkpoints'])
    payload = entries + grid + audio
    crc = zlib.crc32(payload)
    header = struct.pack('<4sIII8s', MAGIC, 1, len(payload), crc, identity)
    image = header.ljust(HEADER_SIZE, b'\xff') + payload
    if len(image) > SLOT_SIZE:
        raise ValueError(f'bank needs {len(image)} bytes: {HEADER_SIZE} header, '
                         f'{len(entries)} entries, {len(grid)} grid, {len(audio)} audio')
    (dest / 'miami.slot').write_bytes(image)
    (dest / 'bgirl_miami_slot.h').write_text(
        '/* Generated by tools/miami_slot.py. */\n'
        f'#define MIAMI_SAMPLES {report["samples"]}u\n'
        f'#define MIAMI_PAYLOAD_BYTES {len(payload)}u\n'
        f'#define MIAMI_PAYLOAD_CRC 0x{crc:08x}u\n'
        f'#define MIAMI_GRID_OFF {HEADER_SIZE + len(entries)}u\n'
        f'#define MIAMI_AUDIO_OFF {HEADER_SIZE + len(entries) + len(grid)}u\n'
        'static const uint8_t MIAMI_HEADER[] = {' + ','.join(map(str, header)) + '};\n')
    print(f'Miami slot: {len(image)} B ({HEADER_SIZE} header, {len(entries)} entries, '
          f'{len(grid)} grid, {len(audio)} audio); {SLOT_SIZE - len(image)} B free')
