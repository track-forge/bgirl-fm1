"""Pack the checked-in 96x96 masks in CREW move order."""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MASKS = (
    "crew/windmill/bgirl_windmill.h",
    "crew/reference-02/bgirl_reference_02.h",
    "crew/wave-ish/bgirl_wave_ish.h",
    "crew/worm/bgirl_worm.h",
    "dance/bgirl_dance.h",
)
POSE_BYTES = 96 * 12


def pack():
    offsets, data = [], bytearray()
    for name in MASKS:
        source = (ROOT / "assets" / name).read_text()
        masks = bytes(int(v, 16) for v in re.findall(r"0x([0-9a-fA-F]{2})\b", source))
        if len(masks) != 12 * POSE_BYTES:
            raise ValueError(f"{name}: expected 12 poses of {POSE_BYTES} bytes")
        for pose in range(0, len(masks), POSE_BYTES):
            offsets.append(len(data))
            for start in range(pose, pose + POSE_BYTES, 12):
                row = masks[start:start + 12]
                span = row.rstrip(b"\0")
                payload = span.lstrip(b"\0")
                first = len(span) - len(payload)
                data.append(first << 4 | len(payload))
                data.extend(payload)
    if len(data) > 65535:
        raise ValueError("packed masks exceed the 16-bit offset range")
    return offsets, data


def main(output):
    offsets, data = pack()
    with Path(output).open("w") as out:
        out.write("/* Generated by tools/pack_dancer_rows.py */\n#pragma once\n")
        out.write("static const uint16_t dancer_pose_offsets[60] = {\n")
        for start in range(0, len(offsets), 12):
            out.write("    " + ", ".join(map(str, offsets[start:start + 12])) + ",\n")
        out.write("};\nstatic const uint8_t dancer_rows[] = {\n")
        for start in range(0, len(data), 24):
            out.write("    " + ", ".join(map(str, data[start:start + 24])) + ",\n")
        out.write("};\n")
    print(f"Dancer rows: {len(data) + 2 * len(offsets)} B packed")


if __name__ == "__main__":
    main(sys.argv[1])
