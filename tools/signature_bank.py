"""Original BGIRL recipes; regenerate checked-in patch bytes and manifest."""
import json
import sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT/'felucca/tools'))
from gen_fm6_patches import op, voice

def pair(name, carrier, mod=None, **kw):
    return voice(name, 5, [carrier, mod or op()] + [op() for _ in range(4)], lpms=0, **kw)
held = dict(r=(88, 65, 65, 75), l=(99, 99, 99, 0))
hit = dict(r=(99, 56, 50, 72), l=(99, 50, 0, 0))
PATCHES = [
    pair('SUB CLEAN', op(ol=96, **held)),
    pair('SUB DRIVE', op(ol=94, **held), op(ol=65, fc=1, **held)),
    pair('IRON STAB', op(ol=96, **hit), op(ol=82, fc=3, ff=41, **hit)),
    pair('EL CHORD', op(ol=88, **hit), op(ol=65, fc=2, **hit)),
    pair('CHIRP', op(ol=94, r=(99,65,55,80), l=(99,0,0,0)),
         pr=(80,65,99,99), pl=(50,50,50,74)),
]
IDS = ['sub-clean','sub-drive','stab-iron','chord-electro','chirp']
NAMES = ['SUB CLEAN','SUB DRIVE','IRON STAB','EL CHORD','CHIRP']
DRUMS = [('bd-round','KICK',12),('sd-snap','SNARE',13),('cp-layer','CLAP',14),
         ('hh-closed','CLOSED HAT',15),('hh-open','OPEN HAT',16)]
def generate():
    lines=['/* SPDX-License-Identifier: GPL-3.0-only */', '/* Generated by tools/signature_bank.py; original BGIRL patches, not ROM data. */',
           'static const uint8_t BG_SIGNATURE_FM[5][155] = {']
    for name,p in zip(NAMES,PATCHES):
        lines += ['    {/* '+name+' */', '        '+','.join(map(str,p))+'},']
    lines += ['};']
    (ROOT/'felucca/firmware/src/signature_patches.h').write_text('\n'.join(lines)+'\n')
    entries=[]
    for i,(id,name,p) in enumerate(zip(IDS,NAMES,PATCHES)):
        entries.append(dict(id=id,name=name,engine=12,preset=8+i,patch=p,
            behavior='mono retrigger' if i<2 else 'minor/+oct four-tone chord' if i==3 else 'poly',
            midi_range=[24,52] if i<2 else [48,72],voices=4 if i==3 else 1,
            rationale='Original reduced sine/FM core; no wavetable or purchased assets',
            controls='OP ENV for amplitude; MLVL for modulator brightness; FM pitch EG for chirp'))
    for i,(id,name,mode) in enumerate(DRUMS):
        entries.append(dict(id=id,name=name,engine=10,preset=4+i,kit=mode,
            behavior='fixed pitch one-shot; shared choke group 1' if i>=3 else 'fixed pitch one-shot',
            tune_semitones=3 if i in (1,2) else 5,voices=1,
            rationale='Original curation of app-owned drum models; clap/body share one allocation',
            controls='TUNE/TONE/DECY/SNAP/ACC/DRV; CLAP LANES SNARE level is BODY balance'))
    (ROOT/'assets/signature').mkdir(exist_ok=True)
    (ROOT/'assets/signature/manifest.json').write_text(json.dumps(dict(version=1,approval='pending Doug listening',sounds=entries),indent=2)+'\n')
if __name__=='__main__': generate()
