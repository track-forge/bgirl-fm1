"""Read identifiers from core.h, descriptor ranges from the actual pinned engine.
Run after tools/generate.py. --check compares without rewriting."""
import json,re,subprocess,sys,tempfile,hashlib
from pathlib import Path
root=Path(__file__).resolve().parents[2]
core=(root/'felucca/firmware/src/core.h').read_text()
core=re.sub(r'/\*.*?\*/','',core,flags=re.S)
def ids(prefix):
    block=next(b for b in re.findall(r'enum\s*\{(.*?)\}',core,re.S) if prefix+'_COUNT' in b)
    return re.findall(r'\b'+prefix+r'_(?!COUNT\b)\w+',block)
with tempfile.TemporaryDirectory() as tmp:
    exe=Path(tmp)/'layout'
    subprocess.run(['cc','-O1','-w','-ffp-contract=off',*[f'-I{root}/felucca/{p}' for p in ['build/gen','firmware/src','firmware/hal','firmware/bsp/chip','firmware/bsp/boards/fm1']],str(root/'tools/song-snapshots/layout.c'),'-lm','-o',str(exe)],check=True)
    layout=json.loads(subprocess.check_output([exe]))
layout.update(parameters=ids('P'),globalIds=ids('G'))
# Built-in sample/phrase identity, independent of build SHA and optional vocal bank.
layout['factoryFingerprint']=hashlib.sha256(b''.join((root/'felucca/build/gen'/n).read_bytes() for n in ['felucca_samples.h','bgirl_speech.h'])).hexdigest()
layout['identity']=hashlib.sha256(json.dumps(layout,sort_keys=True).encode()).hexdigest()[:16]
text='// SPDX-License-Identifier: GPL-3.0-only\n// Generated by tools/song-snapshots/generate_layout.py; do not hand edit.\nexport const layout = '+json.dumps(layout,separators=(',',':'))+';\n'
out=root/'felucca/web/emu/snapshot-layout.mjs'
if '--check' in sys.argv:
    if out.read_text()!=text: raise SystemExit('snapshot descriptor layout is stale')
else: out.write_text(text)
