"""Source-derived UI page manifest; dynamic surfaces are tracked separately."""
import json,re
from pathlib import Path
src=Path('felucca/firmware/src/params.c').read_text().split('static const page_t PAGES[] = {',1)[1].split('\n};',1)[0]
src=re.sub(r'/\*.*?\*/','',src,flags=re.S)
rows=[]
for i,m in enumerate(re.finditer(r'\{"([^"]+)",\s*(FAM_\w+),\s*(SC_\w+),\s*(GR_\w+),\s*\{([^}]+)\}\}',src)):
 title,fam,scope,graph,ids=m.groups()
 phase='LAB' if fam in ['FAM_ENV','FAM_LFO','FAM_FX','FAM_EDIT'] else 'CUT' if fam in ['FAM_SEQ','FAM_GLO'] else 'STAGE' if fam in ['FAM_TRK','FAM_ARP','FAM_SCL'] else 'SYSTEM'
 if title in ['SLICES','LANES','LANES 2','SLICER']:phase='CUT'
 status='approved #36' if title in ['ENV','OPERATOR','OPERATOR 2'] else 'this LAB pass' if phase=='LAB' else 'pending'
 rows.append(dict(index=i,title=title,family=fam,scope=scope,graph=graph,bindings=[s.strip() for s in ids.split(',')],phase=phase,status=status))
Path('docs/ui/pages.json').write_text(json.dumps(rows,indent=2)+'\n')
s='# Firmware page inventory\n\nGenerated by `python3 tools/ui_inventory.py` from `PAGES[]`; indices are source positions, not new navigation IDs.\n\n'
s+=f'{len(rows)} page definitions. Visibility depends on engine, feature flags and context; see the rollout ledger for variants and dynamic surfaces.\n\n'
s+='| Index | Page | Family | Scope | Graph | Knobs | Pass | Status |\n|---:|---|---|---|---|---|---|---|\n'
for r in rows:s+='| '+ ' | '.join([str(r['index']),r['title'],r['family'],r['scope'],r['graph'],', '.join(r['bindings']),r['phase'],r['status']])+' |\n'
Path('docs/ui/PAGES.md').write_text(s)
print(f'{len(rows)} page definitions inventoried')
