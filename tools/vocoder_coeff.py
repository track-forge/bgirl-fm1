import math
from pathlib import Path
h="/* SPDX-License-Identifier: GPL-3.0-only; generated by tools/vocoder_coeff.py. */\n"
for n in (8,12):
 h+=f"static const float BG_COEF{n}[{n}][5] = {{\n"
 for j in range(n):
  w=2*math.pi*(180*(6500/180)**(j/(n-1)))/44100; a=math.sin(w)/(2*(2 if n==8 else 3)); d=1+a
  c=[a/d,0,-a/d,-2*math.cos(w)/d,(1-a)/d]
  h+="{"+",".join(f"{v:.10e}f" for v in c)+"},\n"
 h+="};\n"
(Path(__file__).resolve().parents[1]/"felucca/firmware/src/bgirl_vocoder_coeff.h").write_text(h)
