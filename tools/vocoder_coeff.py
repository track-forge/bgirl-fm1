"""RBJ constant-peak bandpass tables; historical 8/12 generation unchanged."""
import math
from pathlib import Path
BANKS=[('8',8,180,6500,2),('12',12,180,6500,3),('24',24,180,6500,6),('24_WIDE',24,100,9000,5)]
def coefficients(n,lo,hi,q):
 result=[]
 for j in range(n):
  w=2*math.pi*(lo*(hi/lo)**(j/(n-1)))/44100;a=math.sin(w)/(2*q);d=1+a
  result.append([a/d,0,-a/d,-2*math.cos(w)/d,(1-a)/d])
 return result
if __name__=='__main__':
 h='/* SPDX-License-Identifier: GPL-3.0-only; generated by tools/vocoder_coeff.py. */\n'
 for name,n,lo,hi,q in BANKS:
  h+=f'static const float BG_COEF{name}[{n}][5] = {{\n'
  for row in coefficients(n,lo,hi,q):h+='{'+','.join(f'{v:.10e}f' for v in row)+'},\n'
  h+='};\n'
 (Path(__file__).resolve().parents[1]/'felucca/firmware/src/bgirl_vocoder_coeff.h').write_text(h)

 # Bench candidate: scale b0 and a2 by 2^31, and -a1 by 2^30
 # (the latter is nearly 2 at the low end of the bank).
 h='/* SPDX-License-Identifier: GPL-3.0-only; generated by tools/vocoder_coeff.py. */\n'
 for name,n,lo,hi,q in BANKS:
  h+=f'static const int32_t BG_QCOEF{name}[{n}][3] = {{\n'
  for b0,_,_,a1,a2 in coefficients(n,lo,hi,q):
   h+='{'+','.join(str(round(v)) for v in (b0*2**31,-a1*2**30,a2*2**31))+'},\n'
  h+='};\n'
 (Path(__file__).resolve().parents[1]/'felucca/firmware/src/bgirl_vocoder_qcoeff.h').write_text(h)
