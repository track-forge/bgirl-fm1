"""Shared offline release lookup: DSP, display, nearest-value preset lookup."""
from pathlib import Path
values=[5*100**(i/127) for i in range(128)]
h='/* SPDX-License-Identifier: GPL-3.0-only; generated by tools/vocoder_time.py. */\n#ifndef BG_VOCODER_TIME\n#define BG_VOCODER_TIME\n'
h+='static const float BG_REL_MS[128] = {'+','.join(f'{v:.9f}f' for v in values)+'};\n'
h+='''static int bg_release_value(float ms) {
    int best=0;
    for(int i=1;i<128;i++) if ((BG_REL_MS[i]>ms?BG_REL_MS[i]-ms:ms-BG_REL_MS[i]) <
        (BG_REL_MS[best]>ms?BG_REL_MS[best]-ms:ms-BG_REL_MS[best])) best=i;
    return best;
}
#endif
'''
(Path(__file__).resolve().parents[1]/'felucca/firmware/src/bgirl_vocoder_time.h').write_text(h)
